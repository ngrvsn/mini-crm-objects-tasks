'use client'

import { Modal, Tabs } from 'antd'
import type { Role } from '@/lib/types'

const managerGuide = (
  <div className="guide-content">
    <p>
      Вы создаёте объекты, назначаете работу и принимаете результат. Каждая
      задача относится к одному объекту.
    </p>
    <ol>
      <li>
        Откройте «Объекты» и нажмите «Новый объект». Укажите название и адрес.
        Адрес можно выбрать из подсказок или ввести вручную.
      </li>
      <li>
        Откройте объект, нажмите «Новая задача», опишите работу и выберите
        исполнителя.
      </li>
      <li>
        Когда задача окажется «На проверке», откройте её. Нажмите «Принять» или
        «Вернуть на доработку». При возврате обязательно напишите, что
        исправить.
      </li>
      <li>
        Внизу карточки видна история статусов. После принятия задачу уже нельзя
        изменить. Удаление скрывает запись из рабочих списков, но сохраняет
        историю.
      </li>
    </ol>
  </div>
)

const executorGuide = (
  <div className="guide-content">
    <p>Вы видите только назначенные вам задачи и связанные с ними объекты.</p>
    <ol>
      <li>Откройте «Мои задачи» и выберите задачу.</li>
      <li>
        Нажмите «Взять в работу». Когда закончите, нажмите «Отправить на
        проверку».
      </li>
      <li>
        Если задачу вернули, прочитайте комментарий в истории, исправьте работу
        и снова отправьте её на проверку.
      </li>
      <li>
        Вы не можете открыть чужую задачу, создать объект, назначить работу или
        принять свой результат.
      </li>
    </ol>
  </div>
)

export function GuideModal({
  open,
  role,
  onClose
}: {
  open: boolean
  role: Role
  onClose: () => void
}) {
  return (
    <Modal
      title="Как пользоваться мини-CRM"
      open={open}
      onCancel={onClose}
      width={680}
      footer={null}
    >
      <Tabs
        defaultActiveKey={role === 'manager' ? 'manager' : 'executor'}
        items={[
          { key: 'manager', label: 'Я заказчик', children: managerGuide },
          { key: 'executor', label: 'Я исполнитель', children: executorGuide }
        ]}
      />
    </Modal>
  )
}
